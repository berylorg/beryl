use super::*;
use std::io;

const THREAD: &str = "managed-execution-thread";

#[path = "execution/compaction.rs"]
mod compaction;

pub(super) fn serve(socket: &mut WebSocket<TcpStream>, mode: &str) {
    let queued_successor = mode == "execution-next";
    let compaction = matches!(
        mode,
        "execution-compaction" | "execution-compaction-shutdown"
    );
    let successor = queued_successor || compaction;
    let first_ordinal =
        u32::from(successor && std::path::Path::new("execution-started-0.json").exists());
    let mut retained_request = None;
    for ordinal in first_ordinal..if successor { 2 } else { 1 } {
        let Some(first) = retained_request.take().or_else(|| read_projection(socket)) else {
            return;
        };
        let request = if first["method"] == "turn/start" {
            assert_ne!(ordinal, 0, "the first execution needs a real loaded target");
            first
        } else {
            fs::write(
                format!("execution-projection-{ordinal}.json"),
                serde_json::to_vec(&first).unwrap(),
            )
            .unwrap();
            assert_eq!(
                first["method"],
                if ordinal == 0 {
                    "thread/start"
                } else {
                    "thread/resume"
                }
            );
            if ordinal != 0 {
                assert_eq!(first["params"]["threadId"], THREAD);
            }
            project(socket, &first, ordinal != 0);
            read_json(socket)
        };
        fs::write(
            format!("execution-request-{ordinal}.json"),
            serde_json::to_vec(&request).unwrap(),
        )
        .unwrap();
        assert_eq!(request["method"], "turn/start");
        assert_eq!(request["params"]["threadId"], THREAD);
        let input = request["params"]["input"].as_array().unwrap();
        assert_eq!(input.len(), 1);
        assert_eq!(input[0]["type"], "text");
        let text = input[0]["text"].as_str().unwrap();
        let turn = format!("managed-turn-{ordinal}");
        for (method, field, timestamp) in [
            ("item/started", "startedAtMs", 37_001 + ordinal * 10),
            ("item/completed", "completedAtMs", 37_002 + ordinal * 10),
        ] {
            let mut params = json!({
                "item": {"type":"userMessage", "id":format!("managed-user-{ordinal}"), "clientId":null,
                    "content":[{"type":"text", "text":text, "text_elements":[]}]},
                "threadId":THREAD, "turnId":turn
            });
            params[field] = json!(timestamp);
            send_json(socket, json!({"method":method,"params":params}));
        }
        send_json(
            socket,
            json!({"id":request["id"],"result":{"turn":{"id":turn,"items":[],"status":"inProgress"}}}),
        );
        if matches!(mode, "execution-generated" | "execution-generated-awaiting") {
            let path = std::env::current_dir().unwrap().join("generated-source.bin");
            fs::write(&path, b"original generated bytes").unwrap();
            for (method, field, status, at) in [
                ("item/started", "startedAtMs", "inProgress", 37_003),
                ("item/completed", "completedAtMs", "completed", 37_004),
            ] {
                if mode == "execution-generated-awaiting" && method == "item/completed" {
                    continue;
                }
                let notification = format!(
                    r#"{{"method":{method},"params":{{"item":{{"type":"imageGeneration","id":"managed-generated-image","status":{status},"result":"","savedPath":{path}}},"turnId":{turn},"{field}":{at},"threadId":{thread}}}}}"#,
                    method = serde_json::to_string(method).unwrap(),
                    status = serde_json::to_string(status).unwrap(),
                    path = serde_json::to_string(path.to_str().unwrap()).unwrap(),
                    turn = serde_json::to_string(&turn).unwrap(),
                    thread = serde_json::to_string(THREAD).unwrap(),
                );
                socket.send(Message::text(notification)).unwrap();
            }
        }
        fs::write(
            format!("execution-started-{ordinal}.json"),
            serde_json::to_vec(&json!({
                "pid":std::process::id(), "thread":THREAD, "turn":turn, "text":text
            }))
            .unwrap(),
        )
        .unwrap();
        let release = format!("execution-release-{ordinal}");
        if mode == "execution-shutdown" {
            let interrupt = read_json(socket);
            assert_eq!(interrupt["method"], "turn/interrupt");
            assert_eq!(interrupt["params"]["threadId"], THREAD);
            assert_eq!(interrupt["params"]["turnId"], turn);
            send_json(socket, json!({"id":interrupt["id"],"result":{}}));
            fs::write("execution-interrupted", "once").unwrap();
        }
        let deadline = std::time::Instant::now() + Duration::from_secs(10);
        let original_timeout = socket.get_mut().read_timeout().unwrap();
        if queued_successor && ordinal == 0 {
            socket
                .get_mut()
                .set_read_timeout(Some(Duration::from_millis(10)))
                .unwrap();
        }
        while !std::path::Path::new(&release).exists() {
            assert!(
                std::time::Instant::now() < deadline,
                "execution release timed out"
            );
            if queued_successor && ordinal == 0 {
                if !poll_optional_steer(socket) {
                    return;
                }
            } else {
                std::thread::sleep(Duration::from_millis(2));
            }
        }
        socket.get_mut().set_read_timeout(original_timeout).unwrap();
        send_json(
            socket,
            json!({"method":"turn/completed","params":{
                "threadId":THREAD, "turn":{"id":turn,"items":[],"itemsView":"notLoaded","status":"completed","error":null,
                    "startedAt":37_001 + ordinal * 10,
                    "completedAt":if matches!(mode, "execution-generated" | "execution-generated-awaiting") { 37_005 } else { 37_002 + ordinal * 10 },
                    "durationMs":if matches!(mode, "execution-generated" | "execution-generated-awaiting") { 4 } else { 1 }}
            }}),
        );
        if compaction && ordinal == 0 {
            compaction::serve(socket, mode == "execution-compaction-shutdown");
            while let Ok(message) = socket.read() {
                if message.is_close() {
                    return;
                }
                assert!(
                    !message.is_text(),
                    "compaction terminal must retire this connection"
                );
            }
            return;
        }
        let Some(next) = read_projection(socket) else {
            return;
        };
        if next["method"] == "thread/unsubscribe" {
            assert_eq!(next["params"]["threadId"], THREAD);
            send_json(
                socket,
                json!({"id":next["id"],"result":{"status":"unsubscribed"}}),
            );
            fs::write(format!("execution-unsubscribed-{ordinal}"), "ready").unwrap();
        } else {
            assert!(
                successor && ordinal == 0,
                "final execution must settle original unsubscribe cleanup"
            );
            assert!(matches!(
                next["method"].as_str(),
                Some("thread/resume" | "turn/start")
            ));
            assert_eq!(next["params"]["threadId"], THREAD);
            retained_request = Some(next);
        }
    }
    while let Ok(message) = socket.read() {
        if message.is_close() {
            break;
        }
        assert!(
            !message.is_text(),
            "unexpected execution after final terminal capture"
        );
    }
}

fn poll_optional_steer(socket: &mut WebSocket<TcpStream>) -> bool {
    match socket.read() {
        Ok(Message::Text(text)) => {
            let steer: Value = serde_json::from_str(text.as_str()).unwrap();
            assert_eq!(steer["method"], "turn/steer");
            assert_eq!(steer["params"]["threadId"], THREAD);
            assert_eq!(steer["params"]["expectedTurnId"], "managed-turn-0");
            assert!(!std::path::Path::new("execution-steering-denied").exists());
            let id = steer["id"].as_u64().unwrap();
            socket.send(Message::Text(format!(
                r#"{{"error":{{"code":-32600,"data":{{"message":"steering denied","codexErrorInfo":{{"activeTurnNotSteerable":{{"turnKind":"review"}}}},"additionalDetails":null}},"message":"outer steering diagnostic"}},"id":{id}}}"#,
            ).into())).unwrap();
            fs::write("execution-steering-denied", "ready").unwrap();
            true
        }
        Ok(Message::Ping(payload)) => {
            socket.send(Message::Pong(payload)).unwrap();
            true
        }
        Ok(Message::Pong(_) | Message::Frame(_)) => true,
        Ok(Message::Close(_)) => false,
        Err(tungstenite::Error::Io(error))
            if matches!(
                error.kind(),
                io::ErrorKind::WouldBlock | io::ErrorKind::TimedOut
            ) =>
        {
            true
        }
        other => panic!("unexpected active execution control: {other:?}"),
    }
}

fn read_projection(socket: &mut WebSocket<TcpStream>) -> Option<Value> {
    loop {
        match socket.read().unwrap() {
            Message::Text(text) => return Some(serde_json::from_str(text.as_str()).unwrap()),
            Message::Close(_) => return None,
            _ => {}
        }
    }
}

fn project(socket: &mut WebSocket<TcpStream>, request: &Value, resumed: bool) {
    let cwd = env::current_dir().unwrap();
    let mut response = json!({"id":request["id"],"result":{
        "thread":{"id":THREAD,"extra":null,"sessionId":"managed-session","forkedFromId":null,
            "parentThreadId":null,"preview":"","ephemeral":false,"historyMode":"legacy","modelProvider":"openai",
            "createdAt":1,"updatedAt":2,"recencyAt":null,"status":{"type":"idle"},"path":null,
            "cwd":cwd,"cliVersion":"0.146.0","source":"appServer","threadSource":null,
            "agentNickname":null,"agentRole":null,"gitInfo":null,"name":null,"turns":[]},
        "model":"fixture-model","modelProvider":"openai","serviceTier":null,"cwd":cwd,
        "runtimeWorkspaceRoots":[],"instructionSources":[],"approvalPolicy":"never","approvalsReviewer":"user",
        "sandbox":{},"activePermissionProfile":null,"reasoningEffort":null,"multiAgentMode":"explicitRequestOnly"
    }});
    if resumed {
        response["result"]["initialTurnsPage"] = Value::Null;
        response["result"]["turnsBackwardsCursor"] = Value::Null;
        response["result"]["itemsBackwardsCursor"] = Value::Null;
    }
    send_json(socket, response);
}
